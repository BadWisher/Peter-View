def get_registry(include_spelling: bool = True) -> list[dict[str, Any]]:
    rules = REGISTRY if include_spelling else RULES
    return [dict(rule, source_document=STYLE_GUIDE_SOURCE) for rule in rules]


def get_rule(rule_id: str) -> dict[str, Any] | None:
    return next((rule for rule in REGISTRY if rule["id"] == rule_id), None)


def enabled_vale_rule_ids() -> set[str]:
    return {
        rule["id"]
        for rule in RULES
        if rule["engine"] == "vale" and rule["automation"] != "manual"
    }


def style_guide_rule_ids() -> set[str]:
    return {rule["id"] for rule in RULES if rule["automation"] != "manual"}
