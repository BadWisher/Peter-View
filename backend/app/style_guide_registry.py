_PRIORITY_BY_SEVERITY = {"error": 90, "warning": 60, "suggestion": 40}


def _add_authority_metadata(rule: dict[str, Any]) -> None:
    """Дополняет правило метаданными для поиска, не меняя исторический формат реестра."""
    categories = list(dict.fromkeys(
        value for value in (rule.get("group"), str(rule.get("section", "")).split(" / ")[0])
        if value
    ))
    rule.setdefault("categories", categories)
    rule.setdefault("tasks", ["proofreading"])
    rule.setdefault("scope", "all")
    rule.setdefault("priority", _PRIORITY_BY_SEVERITY.get(rule.get("severity"), 50))
    rule.setdefault("mandatory", False)
    rule.setdefault(
        "machine_verifiable",
        rule.get("automation") == "automatic" and rule.get("engine") != "manual",
    )
    rule.setdefault("relationships", {})


for _rule in RULES:
    _add_authority_metadata(_rule)

